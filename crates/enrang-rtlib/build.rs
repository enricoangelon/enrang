//! Embeds `lib/` (ARCHITECTURE 10 "Embedding"): walks the directory in sorted order
//! and writes `$OUT_DIR/lib_table.rs`, a table of `(key, include_str!(path))` sorted
//! by key, where a key is the file's path under `lib/` with `/` separators and no
//! `.en`. Every file and directory is announced with `rerun-if-changed`, so adding,
//! removing or editing a library file rebuilds the table. Only std.

#![forbid(unsafe_code)]

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn walk(dir: &Path, prefix: &str, out: &mut Vec<(String, PathBuf)>) {
    println!("cargo:rerun-if-changed={}", dir.display());
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    let mut entries: Vec<PathBuf> = entries.filter_map(|e| e.ok().map(|e| e.path())).collect();
    entries.sort();
    for path in entries {
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .expect("library file names are UTF-8")
            .to_owned();
        if path.is_dir() {
            walk(&path, &format!("{prefix}{name}/"), out);
        } else if let Some(stem) = name.strip_suffix(".en") {
            println!("cargo:rerun-if-changed={}", path.display());
            out.push((format!("{prefix}{stem}"), path));
        }
    }
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("set by cargo"));
    let lib = manifest.join("../../lib");
    let lib = lib.canonicalize().unwrap_or(lib);
    let mut modules = Vec::new();
    walk(&lib, "", &mut modules);
    modules.sort_by(|a, b| a.0.cmp(&b.0));
    let mut table = String::from(
        "/// Every library module, `(key, source)`, sorted by key (generated by build.rs).\n\
         pub static MODULES: &[(&str, &str)] = &[\n",
    );
    for (key, path) in &modules {
        let path = path.to_str().expect("library paths are UTF-8");
        table.push_str(&format!("    ({key:?}, include_str!({path:?})),\n"));
    }
    table.push_str("];\n");
    let out = PathBuf::from(env::var("OUT_DIR").expect("set by cargo")).join("lib_table.rs");
    fs::write(out, table).expect("the table is written");
}
